import assert from 'node:assert/strict';
import fs from 'node:fs';

const game=fs.readFileSync(new URL('../game.js',import.meta.url),'utf8');

assert.match(game,/const SEASON_3_ID = 'core-breaker-arena-forge-2026-s3'/);
assert.match(game,/const SEASON_3_END_UTC = Date\.UTC\(2026, 8, 21, 0, 0, 0\)/,'Season 3 ends at the start of Sep 21 UTC, after Sep 20');
assert.match(game,/const TOWER_EVENT_MODES_ENABLED = false/);
assert.match(game,/const TOWER_POWER_SYSTEM_ENABLED = false/);
assert.match(game,/packets: \{ schemaVersion:1,/,'new saves include an independent Packet namespace');
assert.match(game,/season3: \{ schemaVersion:SEASON_3_SCHEMA_VERSION,/,'new saves include Season 3 state');
assert.match(game,/packets: playerData\.packets/);
assert.match(game,/season3: playerData\.season3/);
assert.match(game,/ensureSeason3State\(data\.persistent\.packets, data\.persistent\.season3\)/);

const packetIds=['bird','bear','eagle','beetle','ant','dragon','fairy','butterfly','heavy_metal','core','angel','demon','milky','poison','spicy','invisible','ramen','decoy','time','dual_element'];
for(const id of packetIds)assert.match(game,new RegExp(`\\b${id}:\\{id:'${id}'`),`missing Packet definition: ${id}`);
assert.doesNotMatch(game,/PACKET_DEFS[\s\S]{0,12000}\b(activeAbility|abilityButton|active ability)\s*:/i,'Packets must not define active abilities');
assert.match(game,/packets\.equipped=.*PACKET_DEFS\[packets\.equipped\].*packets\.unlocked\[packets\.equipped\]/,'locked Packets cannot remain equipped');
assert.match(game,/function handlePacketMainAttack/);
assert.match(game,/function applyPacketHit/);
assert.match(game,/attack\?\.packetGenerated/,'Packet-generated damage cannot recursively trigger Packets');
assert.match(game,/const packetTimeFields = \[\]/,'Time Packet uses a real world-space field');
assert.match(game,/kind:'eagle'.*impactAt/s,'Eagle Packet has a delayed telegraph');
assert.match(game,/kind:'bear'.*impactAt/s,'Bear Packet has a delayed charge telegraph');
assert.match(game,/\.filter\(id=>!isRetiredTowerMode\(id\)\)/,'retired Tower events are hidden from the public event board');
assert.match(game,/if\(isRetiredTowerMode\(showdownMode\)\)/,'direct attempts to launch retired Tower events safely fall back');

for(const title of ['core_corruptor','corrupted','final_form'])assert.match(game,new RegExp(`${title}:\\{name:`));
assert.match(game,/function initCoreBreachIntro/);
assert.match(game,/\['solo','duo','trio'\]\.includes\(showdownMode\)/,'Core Breach only starts in eligible normal Showdown variants');
assert.match(game,/!isCorruptedShowdownMode/,'Core Breach is isolated from Corrupted Showdown');
assert.match(game,/const CORE_BREACH_DAMAGE_TARGET = 60000/);
assert.match(game,/function recordCoreBreachCombatDamage/);
assert.match(game,/phase\s*=\s*'raid'/);
assert.match(game,/CORE_BALL_MAX_HP/);
assert.match(game,/scaledCoreHp/,'Core Ball HP scales for large Showdown rosters');
for(const kind of ['orb','crack','shockwave'])assert.match(game,new RegExp(`kind:'${kind}'`),`Core Ball is missing its ${kind} phase attack`);
assert.match(game,/findNearestDrySpot\(clamp\(nx/,'Core Ball movement actively avoids invalid terrain');
assert.match(game,/entity\.coreBreachRespawn<3/,'Core raid respawns use a 3-second timer');
assert.match(game,/entity\.invulnerableUntil=now\+1100/,'Core raid respawns receive spawn protection');
assert.match(game,/6 UNKNOWN PACKET SIGNALS DETECTED/);
assert.match(game,/season\.coreBreachCompleted=true/);
assert.match(game,/addPacketSignal\('bird',100,'CORE BREACH',false\)/,'Core Breach awards the first usable Packet');
assert.match(game,/const LAVA_BOSS_DIFFICULTIES/);
assert.match(game,/impossible_15/,'Lava boss ladder reaches Impossible XV');
assert.match(game,/coreSurgeEnabled:index>=8/,'Core Surge begins at Impossible VI, not the early ladder');
assert.match(game,/if\(i===15\)attacks\.push\('eruption'\)/,'Final Core Eruption is exclusive to Impossible XV');
assert.match(game,/function triggerLavaBossSuper/,'Lava boss has dedicated Super attacks');
for(const name of ['MAGMA RUSH','VOLCANO CALL','CORE NOVA'])assert.match(game,new RegExp(name),`missing Lava boss Super: ${name}`);
for(const attack of ['launchLavaBurp','LAVA SLAM','LAVA BEAM','LAVA PUP UPRISING'])assert.match(game,new RegExp(attack),`missing rebuilt Lava boss attack: ${attack}`);
assert.match(game,/const LAVA_PEDESTAL_MAX = 2/,'Lava Pup pedestals have a low hard active cap');
assert.match(game,/const LAVA_PUP_MAX = 4/,'Lava Pups have a low hard active cap');
assert.match(game,/function getLavaPedestalSpawnPads/,'Lava pedestals use authored arena spawn pads');
assert.match(game,/pairs=\[\[0,1\],\[2,3\],\[4,5\]\]/,'Lava pedestal waves occupy mirrored pad pairs');
for(const attack of ['MAGMA SERPENT','MOLTEN PINWHEEL'])assert.match(game,new RegExp(attack),`missing new Lava boss attack: ${attack}`);
assert.match(game,/for\(let i=0;i<2;i\+\+\)bots\.push\(createLavaBossAlly\(i\)\)/,'Lava boss is a true player plus two allies 3v1');
assert.match(game,/LAVA_BOSS_3V1_HP_MULTIPLIER = 0\.72/,'Lava boss HP is retuned for the smaller team');
assert.match(game,/lavaBossRuntime\.pools\.length>32/,'Lava arena pools are capped for performance');
assert.match(game,/lavaBossRuntime\.telegraphs\.length>54/,'Lava attack telegraphs are capped for performance');
assert.match(game,/const packetTimeFields = \[\]/);
assert.match(game,/HOME_PERMANENT_MODE_IDS = \[[^\]]*'lava_boss_s3'/,'Lava boss is permanently playable from Events');
assert.match(game,/id==='impossible_2'\?'core_corruptor'/,'Impossible II grants Core Corruptor');
assert.match(game,/id==='impossible_5'\?'corrupted'/,'Impossible V grants Corrupted');
assert.match(game,/id==='impossible_15'\?'final_form'/,'Impossible XV grants Final Form');
assert.match(game,/const SEASON_PASS_ID = 'core-breaker-arena-forge-2026-s3'/);
assert.match(game,/function isSeason3PassActive/);

console.log('Season 3 schema, Tower retirement, and Packet foundation regression checks passed.');
